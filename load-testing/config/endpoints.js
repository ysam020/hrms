// GET endpoints the workload exercises, with realistic parameters taken from
// the web app's own calls (apps/web/src). Every path is relative to /api/v1.
//
// `roles` is the best-effort expectation of who can use it; scripts/smoke.js
// checks every (role, endpoint) pair against the running stack and the plan
// only keeps pairs that answered 2xx, so the benchmark never pads its
// numbers with 403s a real user would never trigger (the UI hides pages
// people can't open). Dropped pairs are listed in the smoke report.
//
// The full inventory of all 177 GET routes, with why each excluded one is
// excluded, is generated by scripts/inventory.js into
// reports/endpoint-inventory.md.
